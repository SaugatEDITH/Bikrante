// Validation function
function validateLocation(province, district, city) {
    if (!province || !district || !city) return false;

    const provinceData = nepalShippingData[province];
    if (!provinceData) return false;

    const districtData = provinceData[district];
    if (!districtData) return false;

    const cityData = districtData.cities?.[city];
    if (!cityData) return false;

    return true;
}

// Getter function
function getShippingCost(province, district, city) {
    if (!validateLocation(province, district, city)) {
        return null;
    }
    return nepalShippingData[province][district].cities[city].shipping_cost;
}

function getPostalCode(province, district, city) {
    if (!validateLocation(province, district, city)) {
        return null;
    }
    return nepalShippingData[province][district].cities[city].postal_code;
}

function enableDropdown(selectElement) {
    selectElement.addEventListener('change', () => {
        const province = document.getElementById('province').value;
        const district = document.getElementById('district').value;
        const city = document.getElementById('city').value;

        // Update district dropdown based on selected province
        if (selectElement.id === 'province') {
            const districtSelect = document.getElementById('district');
            const citySelect = document.getElementById('city');
            districtSelect.innerHTML = '<option value="">Select District</option>';
            citySelect.innerHTML = '<option value="">Select City</option>';
            document.getElementById('postcode').value = '';

            if (province && nepalShippingData[province]) {
                const districts = Object.keys(nepalShippingData[province]);
                districts.forEach(district => {
                    const option = document.createElement('option');
                    option.value = district;
                    option.textContent = district;
                    districtSelect.appendChild(option);
                });
            }
        }

        // Update city dropdown based on selected district
        if (selectElement.id === 'district') {
            const citySelect = document.getElementById('city');
            citySelect.innerHTML = '<option value="">Select City</option>';
            document.getElementById('postcode').value = '';

            if (province && district && nepalShippingData[province]?.[district]) {
                const cities = Object.keys(nepalShippingData[province][district].cities);
                cities.forEach(city => {
                    const option = document.createElement('option');
                    option.value = city;
                    option.textContent = city;
                    citySelect.appendChild(option);
                });
            }
        }

        // Update postcode based on selected city
        if (selectElement.id === 'city') {
            const postcodeInput = document.getElementById('postcode');
            if (province && district && city && nepalShippingData[province]?.[district]?.cities[city]) {
                postcodeInput.value = nepalShippingData[province][district].cities[city].postal_code || '';
            } else {
                postcodeInput.value = '';
            }
        }
    });
}

// Optimize by adding event listeners only once
document.addEventListener('DOMContentLoaded', () => {
    enableDropdown(document.getElementById('province'));
    enableDropdown(document.getElementById('district'));
    enableDropdown(document.getElementById('city'));
});
